#! /usr/bin/env python
"""Resolve public PDF links for the publications and record them in _data/oa_links.yml.

For every entry in the Paperpile export the link is chosen in this order:

    1. override   `pdf_overrides: {bibkey: url}` in _data/pubinfo.yml
    2. unpaywall  a direct PDF url from Unpaywall (by DOI)
    3. europepmc  the open-access PDF on Europe PMC / PMC (by DOI -> PMCID)
    4. bucket     `{pdf_bucket_base}/{bibkey}.pdf`, only for bibkeys listed under
                  `pdf_bucket:` in pubinfo.yml and only when a bucket base is configured
    5. landing    https://doi.org/<doi> (kind: landing; not a PDF)

Entries without a DOI get a link only from 1 or 4; otherwise a warning is printed.

The manifest is keyed by bibkey. `bin/update_references.py` reads it (offline) to set the
`pdf` / `html` fields, so this script is the only one that touches the network. Failures
only warn: the script exits non-zero only when an input cannot be read.
"""

import argparse
import sys
import time
from datetime import date
from pathlib import Path
from typing import Any, Dict, List, Optional

import requests
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from update_references import (  # noqa: E402
    REPO_ROOT,
    PipelineError,
    bib_fromfile,
    info,
    norm_doi,
    warn,
    yaml_fromfile,
)

DEFAULT_EMAIL = "bendall@gwu.edu"
PDF_KINDS = ("pdf", "override", "bucket")  # kinds whose link is a PDF (landing is not)
MANIFEST_HEADER = (
    "# Public PDF links, keyed by bibkey. Generated by bin/resolve_links.py.\n"
    "# kind: pdf (open-access PDF) | override (pdf_overrides in pubinfo.yml) |\n"
    "#       bucket ({pdf_bucket_base}/<bibkey>.pdf) | landing (https://doi.org/<doi>, not a PDF)\n"
    "# Safe to edit by hand; entries with kind pdf/override/bucket are not re-resolved\n"
    "# unless --refresh is given, and kind landing is retried on every run.\n"
)


""" HTTP """


class Http:
    """Small polite JSON client: timeout, retries with backoff, pause between requests."""

    def __init__(self, email: str, pause: float = 0.5, timeout: float = 20.0, retries: int = 3):
        self.session = requests.Session()
        self.session.headers["User-Agent"] = f"bendall-lab-refs/0.1 (mailto:{email})"
        self.pause, self.timeout, self.retries = pause, timeout, retries
        self._last = 0.0

    def get_json(self, url: str, params: Optional[Dict[str, str]] = None) -> Optional[Dict[str, Any]]:
        """Return the decoded JSON, or None on 404 / persistent failure (a warning is printed)."""
        for attempt in range(self.retries + 1):
            wait = self.pause - (time.monotonic() - self._last)
            if wait > 0:
                time.sleep(wait)
            try:
                resp = self.session.get(url, params=params, timeout=self.timeout)
            except requests.RequestException as e:
                err = str(e)
            else:
                self._last = time.monotonic()
                if resp.status_code == 404:
                    return None
                if resp.status_code == 200:
                    try:
                        return resp.json()
                    except ValueError:
                        err = "response was not JSON"
                else:
                    err = f"HTTP {resp.status_code}"
                    if resp.status_code not in (429, 500, 502, 503, 504):
                        break
            if attempt < self.retries:
                delay = 2 ** (attempt + 1)
                info(f"  retrying {url} in {delay}s ({err})")
                time.sleep(delay)
        warn(f"request failed: {url} ({err})")
        return None


""" Sources """


def _norm_license(s: Optional[str]) -> Optional[str]:
    return s.strip().lower().replace(" ", "-") if isinstance(s, str) and s.strip() else None


def query_unpaywall(http, doi: str, email: str) -> Optional[Dict[str, Any]]:
    """Direct PDF url (best location first), license and OA flag from Unpaywall.

    Unpaywall often knows a paper is open access but has no direct PDF url; then `pdf` is
    None (its landing-page "url" is deliberately ignored; it is not a PDF)."""
    data = http.get_json(f"https://api.unpaywall.org/v2/{doi}", {"email": email})
    if not data:
        return None
    locs = [data.get("best_oa_location")] + list(data.get("oa_locations") or [])
    locs = [l for l in locs if l]
    pdf, lic = None, None
    for loc in locs:
        if loc.get("url_for_pdf"):
            pdf, lic = loc["url_for_pdf"], _norm_license(loc.get("license"))
            break
    if lic is None and locs:
        lic = _norm_license(locs[0].get("license"))
    return {"is_oa": bool(data.get("is_oa")), "license": lic, "pdf": pdf}


def query_europepmc(http, doi: str) -> Optional[Dict[str, Any]]:
    """PMCID, license and open-access PDF link from the Europe PMC search API."""
    data = http.get_json(
        "https://www.ebi.ac.uk/europepmc/webservices/rest/search",
        {"query": f'DOI:"{doi}"', "format": "json", "resultType": "core", "pageSize": "5"},
    )
    results = ((data or {}).get("resultList") or {}).get("result") or []
    hit = next((r for r in results if norm_doi(r.get("doi")) == doi), None)
    if not hit:
        return None
    pmcid = hit.get("pmcid")
    is_oa = hit.get("isOpenAccess") == "Y"
    pdf = None
    urls = (hit.get("fullTextUrlList") or {}).get("fullTextUrl") or []
    for u in urls:
        if u.get("documentStyle") == "pdf" and u.get("availability") == "Open access":
            pdf = u.get("url")
            if u.get("site") == "Europe_PMC":
                break
    if pdf is None and pmcid and is_oa:
        pdf = f"https://europepmc.org/articles/{pmcid}?pdf=render"
    return {"pmcid": pmcid, "is_oa": is_oa, "license": _norm_license(hit.get("license")), "pdf": pdf}


""" Resolution """


def _clean(d: Dict[str, Any]) -> Dict[str, Any]:
    return {k: v for k, v in d.items() if v is not None}


def resolve_entry(
    key: str,
    doi: Optional[str],
    http,
    email: str,
    existing: Optional[Dict[str, Any]] = None,
    overrides: Optional[Dict[str, str]] = None,
    bucket_base: Optional[str] = None,
    bucket_keys: Optional[set] = None,
    only_missing: bool = True,
) -> Optional[Dict[str, Any]]:
    """Return the manifest record (without `resolved`) for one entry, or None for no link."""
    overrides = overrides or {}
    bucket_keys = bucket_keys or set()
    bucket_url = f"{bucket_base.rstrip('/')}/{key}.pdf" if bucket_base and key in bucket_keys else None
    kind = (existing or {}).get("kind")

    if key in overrides:
        return _clean({"pdf": overrides[key], "kind": "override", "source": "pubinfo", "doi": doi})
    if only_missing and kind == "pdf":
        return {k: v for k, v in existing.items() if k != "resolved"}
    if only_missing and kind == "bucket" and bucket_url:
        return _clean({"pdf": bucket_url, "kind": "bucket", "source": "bucket", "doi": doi})

    up = epmc = None
    if doi:
        up = query_unpaywall(http, doi, email)
        epmc = query_europepmc(http, doi)
    meta = {
        "doi": doi,
        "pmcid": (epmc or {}).get("pmcid"),
        "is_oa": True if (up or {}).get("is_oa") or (epmc or {}).get("is_oa") else (False if (up or epmc) else None),
    }
    if up and up["pdf"]:
        return _clean({**meta, "pdf": up["pdf"], "kind": "pdf", "source": "unpaywall",
                       "license": up["license"] or (epmc or {}).get("license")})
    if epmc and epmc["pdf"]:
        return _clean({**meta, "pdf": epmc["pdf"], "kind": "pdf", "source": "europepmc",
                       "license": epmc["license"] or (up or {}).get("license")})
    if bucket_url:
        return _clean({**meta, "pdf": bucket_url, "kind": "bucket", "source": "bucket"})
    if doi:
        return _clean({**meta, "pdf": f"https://doi.org/{doi}", "kind": "landing", "source": "doi",
                       "license": (up or {}).get("license") or (epmc or {}).get("license")})
    return None


def resolve_all(
    entries: List[Dict[str, Any]],
    manifest: Dict[str, Any],
    http,
    email: str,
    overrides: Dict[str, str],
    bucket_base: Optional[str],
    bucket_keys: set,
    only_missing: bool = True,
    skip_keys: Optional[set] = None,
    today: Optional[str] = None,
) -> Dict[str, Any]:
    """Return the updated manifest. `resolved` changes only when a record's content does."""
    today = today or date.today().isoformat()
    skip_keys = skip_keys or set()
    out = dict(manifest)
    for e in entries:
        key = e["ID"]
        if key in skip_keys:
            info(f"{key}: skipped (preprint with a published version).")
            continue
        doi = norm_doi(e.get("doi"))
        rec = resolve_entry(key, doi, http, email, manifest.get(key), overrides,
                            bucket_base, bucket_keys, only_missing)
        if rec is None:
            warn(f"{key}: no DOI and no override; add `pdf_overrides` or list it under `pdf_bucket` in pubinfo.yml.")
            out.pop(key, None)
            continue
        old = manifest.get(key) or {}
        if {k: v for k, v in old.items() if k != "resolved"} == rec:
            rec["resolved"] = old.get("resolved", today)
            info(f"{key}: unchanged ({rec['kind']}).")
        else:
            rec["resolved"] = today
            detail = f" {rec.get('pmcid')}" if rec.get("pmcid") else ""
            info(f"{key}: {rec['kind']} via {rec['source']}{detail}")
        out[key] = rec
    return out


def dump_manifest(manifest: Dict[str, Any]) -> str:
    body = yaml.safe_dump(manifest, sort_keys=True, allow_unicode=True, width=1000, default_flow_style=False)
    return MANIFEST_HEADER + body


""" CLI """


def parse_args(argv=None) -> argparse.Namespace:
    def rel(p):
        return str(REPO_ROOT / p)

    ap = argparse.ArgumentParser(description="Resolve public PDF links into _data/oa_links.yml.")
    ap.add_argument("--paperpile", default=rel("_bibliography/paperpile.bib"), type=Path)
    ap.add_argument("--manifest", default=rel("_data/oa_links.yml"), type=Path)
    ap.add_argument("--pubinfo", default=rel("_data/pubinfo.yml"), type=Path)
    ap.add_argument("--email", default=DEFAULT_EMAIL, help="contact email (required by Unpaywall)")
    ap.add_argument("--bucket-base", default=None, help="public bucket base URL (overrides pubinfo.yml `pdf_bucket_base`)")
    ap.add_argument("--only-missing", action=argparse.BooleanOptionalAction, default=True,
                    help="keep existing kind pdf/bucket records (default); --no-only-missing or --refresh re-resolves")
    ap.add_argument("--refresh", action="store_true", help="re-resolve every entry")
    ap.add_argument("--bibkey", action="append", default=None, metavar="KEY",
                    help="only resolve this bibkey (repeatable)")
    ap.add_argument("--dry-run", action="store_true", help="print the manifest; write nothing")
    return ap.parse_args(argv)


def main(argv=None, http=None) -> int:
    args = parse_args(argv)
    try:
        entries = bib_fromfile(args.paperpile).entries
        pubinfo = yaml_fromfile(args.pubinfo)
        manifest = yaml_fromfile(args.manifest) if args.manifest.is_file() else {}
    except PipelineError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    if not isinstance(manifest, dict):
        print(f"Error: {args.manifest} is not a mapping.", file=sys.stderr)
        return 1

    only_missing = args.only_missing and not args.refresh
    if args.bibkey:
        unknown = set(args.bibkey) - {e["ID"] for e in entries}
        for k in sorted(unknown):
            warn(f"--bibkey {k} not found in {args.paperpile}")
        entries = [e for e in entries if e["ID"] in args.bibkey]

    # Preprints that have a published version in the bibliography are dropped by
    # update_references.py, so don't resolve them.
    by_doi = {norm_doi(e.get("doi")) for e in entries}
    skip = set()
    for pair in pubinfo.get("preprint_published") or []:
        pre, pub = norm_doi(pair.get("preprint")), norm_doi(pair.get("published"))
        if pre in by_doi and pub in by_doi:
            skip |= {e["ID"] for e in entries if norm_doi(e.get("doi")) == pre}

    http = http or Http(args.email)
    new = resolve_all(
        entries, manifest, http, args.email,
        overrides=pubinfo.get("pdf_overrides") or {},
        bucket_base=args.bucket_base or pubinfo.get("pdf_bucket_base"),
        bucket_keys=set(pubinfo.get("pdf_bucket") or []),
        only_missing=only_missing,
        skip_keys=skip,
    )

    if not args.bibkey:  # drop records for bibkeys that no longer exist in the export
        present = {e["ID"] for e in entries}
        for k in sorted(set(new) - present):
            info(f"{k}: removed from manifest (not in {args.paperpile.name}).")
            del new[k]

    kinds: Dict[str, int] = {}
    for rec in new.values():
        kinds[rec["kind"]] = kinds.get(rec["kind"], 0) + 1
    info("Manifest: " + ", ".join(f"{n} {k}" for k, n in sorted(kinds.items())) + f" ({len(new)} entries).")

    text = dump_manifest(new)
    if args.dry_run:
        print(text)
        return 0
    current = args.manifest.read_text() if args.manifest.is_file() else ""
    if text != current:
        args.manifest.write_text(text)
        info(f"Wrote {args.manifest}.")
    else:
        info(f"{args.manifest} unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
